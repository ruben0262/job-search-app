"""The setup conversations: one thread per chat, replayed into every request.

The reference instance runs its setup agents as slash commands in a terminal, where the transcript
is the terminal. A hosted product has no terminal, so the transcript is a table — and it has to be,
because `/setup-prompts` and `/setup-scorer` both assume `/setup` already ran and its answers are
still visible.

**Several conversations per account, each with its own context** (owner, 2026-07-30). One endless
thread was the wrong shape for the same reason it is wrong in every chat product: a question about
this week's job search does not want six weeks of profile interview in front of it, and starting
fresh should not mean losing what was said before. So a conversation is a row, messages belong to
one, and the model only ever sees the one being spoken in.

**What is shared across conversations is the profile itself.** The files are the durable state —
every chat reads and writes the same `context.md`. That asymmetry is the point: the transcript is
scratch, the files are the product, and a new chat starts with a clean transcript and the full
profile rather than a blank slate.
"""
from __future__ import annotations

import uuid

from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    ForeignKey,
    Index,
    String,
    Text,
    func,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column

from libs.db.base import Base, timestamptz

# The commands a user can run in the chat. Ported from `.claude/commands/`; the first is the one
# that has to run before either of the others will start.
SETUP_AGENTS = ("setup-director", "setup-context", "setup", "setup-prompts",
                "setup-role-angles", "setup-scorer")

# How many conversations one account may keep. **Fixed, and not a user setting** (owner,
# 2026-07-30). Each one replays its whole transcript into every turn on the user's own credential,
# so an account with twenty half-finished chats is an account paying to re-read them; three is
# enough to keep a long profile interview, a current thread, and one scratch conversation apart.
# Deleting one is how you make room, which is why delete exists.
MAX_CONVERSATIONS = 3

# What a conversation is called before anybody has said anything in it. **Not "New chat"**, which
# is what the button that creates one says: two identical labels sitting next to each other in the
# switcher, and the first browser run clicked the wrong one.
DEFAULT_TITLE = "Untitled chat"


class SetupConversation(Base):
    """One chat thread. The unit of context."""

    __tablename__ = "setup_conversations"

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid.uuid4)
    user_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id", ondelete="CASCADE"))

    # Derived from the first thing the user says, not asked for and not generated by a model —
    # a title is worth zero tokens and a naming call would be one more thing to fail.
    title: Mapped[str] = mapped_column(String(80), default=DEFAULT_TITLE)

    created_at: Mapped[timestamptz] = mapped_column(server_default=func.now())
    # Ordering key for the list, so the chat you are actually in sits at the top.
    last_message_at: Mapped[timestamptz | None]

    __table_args__ = (
        Index("ix_setup_conversations_user", "user_id", "last_message_at"),
    )


class SetupMessage(Base):
    """One turn of one conversation."""

    __tablename__ = "setup_messages"

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    user_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id", ondelete="CASCADE"))
    # **The context boundary.** Every read filters on it, so one chat can never see another's
    # transcript. Cascades: deleting a conversation is deleting what was said in it.
    conversation_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("setup_conversations.id", ondelete="CASCADE"))

    role: Mapped[str] = mapped_column(String(16))
    content: Mapped[str] = mapped_column(Text)

    # **How far this turn has got.** A user row is always `done`; an assistant row is created
    # `pending`, moves to `streaming` as text arrives, and ends `done` or `failed`.
    #
    # It lives on the message rather than in the queue because the transcript is what the page
    # reads, and a pending row *is* the thinking state — so a worker that dies mid-turn leaves
    # something the reader can be told about rather than a gap nothing explains.
    status: Mapped[str] = mapped_column(String(16), default="done")
    # Why it failed, in the words the reader gets. Null unless `status = 'failed'`.
    error: Mapped[str | None] = mapped_column(Text)

    # Which command was driving. Null for a message sent outside one.
    agent: Mapped[str | None] = mapped_column(String(32))

    # The assistant's tool calls and their results, in the shape the API takes them back. Replayed
    # so the model can see the file it just wrote rather than being told about it.
    tool_calls: Mapped[list | None] = mapped_column(JSONB)

    created_at: Mapped[timestamptz] = mapped_column(server_default=func.now())

    __table_args__ = (
        # The only query this table has: one conversation's transcript, oldest first.
        Index("ix_setup_messages_conversation", "conversation_id", "id"),
        Index("ix_setup_messages_user", "user_id", "id"),
        CheckConstraint("role IN ('user', 'assistant')", name="setup_messages_role"),
        # `cancelling` is the user having asked to stop and the worker not having noticed yet — it
        # checks between tool steps, which is the only safe seam in a turn that is mid-HTTP-call.
        # `cancelled` is a finished state and deliberately not `failed`: nothing went wrong, and
        # showing somebody their own decision as an error is untrue.
        CheckConstraint(
            "status IN ('pending', 'streaming', 'done', 'failed', 'cancelling', 'cancelled')",
            name="setup_messages_status"),
    )
