"""Dedup keys: canonical URL and cross-source content key.

**A faithful port of `job-search/pipeline/lib/store.py`.** Behaviour is pinned byte-for-byte by
`tests/test_dedup_parity.py` (T2) against goldens generated by executing the reference itself.
Changing an output here is not a refactor — it changes which jobs the platform considers the same
job, and the failure mode is silent: duplicates in every user's feed, or a real posting quietly
swallowed. If a golden fails, that is the finding.

The two layers, and why there are two:

1. **`canonical_url`** — the same job arrives under unrelated URLs (`linkedin.com/jobs/view/…` from
   the LinkedIn scrape, `boards.greenhouse.io/…` from the direct-ATS poll). URL equality cannot see
   that, so both sides compare canonical forms: host lowercased and `www.`-stripped, the two
   Greenhouse hosts folded together, query/fragment/trailing slash dropped.
2. **`content_key`** — catches the same role reposted across boards even when no apply URL is
   resolvable. Normalised company + title + **location**.

**Location is part of the content key, deliberately.** The same title in two cities is two jobs and
must never be collapsed. The cost is that sources writing a location differently ("London" vs
"London, UK") produce different keys — a missed dedup, which is the safe direction to fail, and the
canonical-URL layer usually catches it anyway.

One thing the reference's own comment gets wrong, preserved here because the behaviour is what
matters: it claims `"Remote" == "Remote - EMEA" == ""`. It does not. The noise list strips `remote`,
so `"Remote"` yields no location component, but `EMEA` survives and `"Remote - EMEA"` keys as
`…|emea`. The two do **not** collapse. Pinned by the goldens; see `tests/test_dedup_parity.py`.
"""
from __future__ import annotations

import re
from urllib.parse import urlparse

# "(Remote)", "(m/f/d)", "(EU)" — parenthesised groups are dropped wholesale before tokenising.
_PAREN_RE = re.compile(r"\([^)]*\)")
_NON_ALNUM_RE = re.compile(r"[^a-z0-9]+")

# Words that describe *arrangement*, not identity. A "Remote Senior Engineer" and a "Senior
# Engineer" at the same company are the same posting.
_TITLE_NOISE = {"remote", "hybrid", "onsite", "fully"}
_LOC_NOISE = {"remote", "hybrid", "onsite", "on", "site", "fully", "based"}

# Legal-entity suffixes. Stripped so "Acme" and "Acme Ltd" key together — but never down to nothing,
# which is why the caller's loop guards on len > 1: a company genuinely named "Co" or "AB" survives.
_COMPANY_SUFFIX = {"inc", "ltd", "llc", "gmbh", "kft", "bv", "ag", "co", "corp",
                   "limited", "srl", "sro", "zrt", "plc", "ab", "as", "oy"}

# job-boards.greenhouse.io and boards.greenhouse.io are the same board behind two hostnames.
_GH_HOST = {"job-boards.greenhouse.io": "boards.greenhouse.io"}


def _norm_tokens(s: str) -> list[str]:
    """Lowercase, drop parenthesised groups, split on anything non-alphanumeric."""
    return [t for t in _NON_ALNUM_RE.sub(" ", _PAREN_RE.sub(" ", (s or "").lower())).split() if t]


def content_key(title: str, company: str, location: str = "") -> str | None:
    """Stable cross-source identity for a job, or ``None`` if title/company is unusable.

    ``None`` means "no opinion" and the caller must **fail open** — treat the job as new rather than
    as a duplicate of everything else that also produced ``None``. Collapsing on an absent key would
    silently discard every posting with an unparseable title.
    """
    t = [w for w in _norm_tokens(title) if w not in _TITLE_NOISE]
    c = _norm_tokens(company)
    while len(c) > 1 and c[-1] in _COMPANY_SUFFIX:
        c.pop()
    if not t or not c:
        return None
    loc = [w for w in _norm_tokens(location) if w not in _LOC_NOISE]
    return " ".join(c) + "|" + " ".join(t) + ("|" + " ".join(loc) if loc else "")


def canonical_url(url: str) -> str | None:
    """Host + path, stripped of everything that varies without changing the job.

    ``None`` for anything with no network location — empty strings, relative paths, junk. Callers
    fail open on ``None`` for the same reason as ``content_key``.

    Note the scheme is discarded, so ``http://`` and ``https://`` forms of a URL are the same job.
    """
    p = urlparse((url or "").strip())
    if not p.netloc:
        return None
    host = p.netloc.lower().removeprefix("www.")
    host = _GH_HOST.get(host, host)
    return f"{host}{p.path.rstrip('/')}".lower()   # boards are case-insensitive on tokens
